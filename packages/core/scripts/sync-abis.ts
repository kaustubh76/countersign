/**
 * Regenerates src/abi.ts from the Foundry build output so the TypeScript side can never drift from the
 * deployed contracts. Run after `forge build`:  pnpm --filter @countersign/core sync-abis
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");
const contracts = [
  ["skillRegistryAbi", "SkillRegistry.sol/SkillRegistry.json"],
  ["countersignAbi", "Countersign.sol/Countersign.json"],
  ["agentIdAbi", "IAgentID.sol/IAgentID.json"],
] as const;

let body = "// GENERATED by scripts/sync-abis.ts from contracts/out. Do not edit by hand.\n\n";
for (const [name, path] of contracts) {
  const { abi } = JSON.parse(readFileSync(resolve(out, path), "utf8"));
  body += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(resolve(here, "../src/abi.ts"), body);
console.log(`wrote src/abi.ts (${contracts.length} ABIs)`);
